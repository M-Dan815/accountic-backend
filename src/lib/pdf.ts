import puppeteer, { type Browser } from "puppeteer";
import { formatSar } from "@/modules/statements/accountTree";

/**
 * HTML → PDF via headless Chromium.
 *
 * Why a browser for PDFs: the statements are bilingual EN/AR and must render
 * with real Arabic shaping + bidi and a right-to-left layout. Browsers do
 * all of that natively; pure-JS PDF libs render Arabic as disconnected,
 * reversed glyphs. One lazy browser instance is reused across exports, so
 * only the first PDF pays the launch cost.
 */

let browserPromise: Promise<Browser> | null = null;

function getBrowser() {
  browserPromise ??= puppeteer.launch({
    args: ["--no-sandbox", "--disable-dev-shm-usage"],
  });
  return browserPromise;
}

export async function htmlToPdf(html: string): Promise<Buffer> {
  const browser = await getBrowser();
  const page = await browser.newPage();
  try {
    await page.setContent(html, { waitUntil: "load" });
    const bytes = await page.pdf({
      format: "A4",
      printBackground: true,
      margin: { top: "16mm", bottom: "20mm", left: "14mm", right: "14mm" },
      displayHeaderFooter: true,
      headerTemplate: "<span></span>",
      footerTemplate:
        '<div style="width:100%;font-size:8px;color:#8a8577;text-align:center;font-family:sans-serif;">' +
        'Generated by Rasid — <span class="pageNumber"></span>/<span class="totalPages"></span></div>',
    });
    return Buffer.from(bytes);
  } finally {
    await page.close();
  }
}

