import { Router } from "express";
import { z } from "zod";
import {
  getCaseByClientToken,
  answerClarification,
} from "@/modules/cases/clarification.service";
import { badRequest, notFound } from "@/lib/http-error";

/**
 * PUBLIC, UNAUTHENTICATED endpoints that back the client-facing
 * clarification portal the client asked us to structure for.
 *
 *   "please structure it so that we can later have 'Request clarification
 *    from client / طلب توضيح من العميل', where AccountTech collects the
 *    unclear transactions and the client simply explains what they were."
 *
 * Authentication is via a per-case bearer token generated by the
 * accountant from the authenticated side (see POST
 * /api/cases/:caseId/clarifications/request in documents.routes.ts).
 * The token is single-purpose: it exposes ONLY the case's open
 * clarifications and nothing else. It expires, and it can be revoked by
 * rotating.
 *
 * Mounted BEFORE the requireAuth middleware in app.ts.
 *
 * ─── PATTERN HYPOTHESIS EXTENSION ──────────────────────────────────────
 * Each clarification MAY carry an AI-proposed account + reason (see
 * patternDetector.ts + ai-provider.ts → suggestClarificationQuestion +
 * processing.service.ts → raiseExceptions). When present, the GET endpoint
 * exposes them so the client portal can render:
 *
 *   "These 5 payments of ~4,850 SAR each were made to احمد محمد on the
 *    1st of every month. What are these — salaries?
 *
 *    AI suggests: 5102 — Salaries and Wages
 *    Reason: 5 monthly outflows on day 1 to the same payee, amounts within 2%.
 *
 *    [ Yes, that's right ]   [ No, these are... ]"
 *
 * The "Yes" button hits the POST endpoint with `confirmHypothesis: true`.
 * The handler then passes the clarification's `proposedAccountId` through
 * to `answerClarification`, which already invokes `learnFromDecision`
 * → `propagateToPayeeSiblings` and so settles EVERY pending sibling
 * transaction to the same payee in one click. That's the spec's
 * "with one click, all statements in the group should be assigned to a
 * particular account" requirement, delivered on the client portal side
 * (the accountant side already had it via manual_category in
 * cases.routes.ts).
 */
export const publicClarificationsRouter = Router();

publicClarificationsRouter.get("/clarifications/:token", async (req, res) => {
  const ctx = await getCaseByClientToken(req.params.token);
  if (!ctx) throw notFound("This link is invalid or has expired.");

  res.json({
    case: {
      id: ctx.id,
      label: ctx.label,
      clientName: ctx.client.name,
      clientNameAr: ctx.client.nameAr,
      periodStart: ctx.periodStart,
      periodEnd: ctx.periodEnd,
      // `firm` is composed onto the lookup result by the service — see
      // getCaseByClientToken. It is not a Prisma relation on Case.
      firmName: ctx.firm?.name ?? null,
      firmNameAr: ctx.firm?.nameAr ?? null,
    },
    // Only what the client needs to see: the transaction itself, the
    // question being asked, and (when present) the AI's proposed account
    // + reason + the detected-pattern summary so the client can see WHY
    // the AI thinks this is salaries. Internal ids are exposed because
    // they are the addressing scheme for the answer endpoint.
    clarifications: ctx.clarifications.map((c) => ({
      id: c.id,
      transaction: c.bankTransaction
        ? {
            date: c.bankTransaction.date,
            description: c.bankTransaction.description,
            amount: Number(c.bankTransaction.amount),
            reference: c.bankTransaction.reference,
          }
        : null,
      question: c.question,
      questionAr: c.questionAr,
      // Multiple-choice options (Q01–Q10): only what a client can answer — an option that maps to an
      // account, or a short list to pick from. Accountant-only options (split, pick any account) are hidden.
      choices: publicChoices(c.options),
      // AI hypothesis block — null when no hypothesis was generated.
      // The portal renders a one-click "Yes, that's right" button only
      // when `proposedAccount` is non-null.
      hypothesis:
        c.proposedAccount && c.hypothesisReason
          ? {
              proposedAccount: {
                id: c.proposedAccount.id,
                code: c.proposedAccount.code,
                name: c.proposedAccount.name,
                nameAr: c.proposedAccount.nameAr,
              },
              reason: c.hypothesisReason,
              // The raw detected signals (cadence, day-of-month, amount
              // range) — let the UI show "why did the AI think this?"
              detectedPattern: c.detectedPattern,
            }
          : null,
    })),
  });
});

const answerSchema = z.object({
  // The client always types something — even on a one-click confirm, the
  // portal pre-fills this with something like "Confirmed: yes, these are
  // salaries". The text is the audit trail.
  answer: z.string().min(1),
  // When true: the client is confirming the AI's proposed account. The
  // handler fetches the clarification's `proposedAccountId` (the client
  // doesn't know account codes) and passes it through to
  // `answerClarification`, which triggers `learnFromDecision` and so
  // settles every sibling transaction to the same payee.
  confirmHypothesis: z.boolean().optional().default(false),
  // The client tapped one of the multiple-choice options (must be one that this question offers).
  optionAccountId: z.string().optional(),
});

type Opt = { label: string; kind: string; account?: { id: string; nameAr: string | null; name: string }; choices?: { id: string; nameAr: string | null; name: string }[] };
function optionsOf(raw: unknown): Opt[] {
  return ((raw as { question?: { options?: Opt[] } } | null)?.question?.options ?? []).filter((o) => !o.kind || ["account", "choose"].includes(o.kind));
}
/** [{label, accountId, accountName}] — one entry per tappable answer. */
function publicChoices(raw: unknown) {
  return optionsOf(raw).flatMap((o) =>
    o.kind === "account" && o.account ? [{ label: o.label, accountId: o.account.id, accountName: o.account.nameAr ?? o.account.name }]
    : o.kind === "choose" ? (o.choices ?? []).map((a) => ({ label: `${o.label} — ${a.nameAr ?? a.name}`, accountId: a.id, accountName: a.nameAr ?? a.name }))
    : []);
}

publicClarificationsRouter.post(
  "/clarifications/:token/answer/:clarificationId",
  async (req, res) => {
    const ctx = await getCaseByClientToken(req.params.token);
    if (!ctx) throw notFound("This link is invalid or has expired.");

    const c = ctx.clarifications.find(
      (x) => x.id === req.params.clarificationId,
    );
    if (!c) throw badRequest("That question is not part of this link.");

    const body = answerSchema.parse(req.body);

    // Resolve the proposed account to actually apply. Only when the
    // client explicitly confirms the hypothesis AND the clarification
    // actually carries one. A question with no hypothesis is just a
    // question — the answer is recorded as text and the accountant still
    // has to categorise afterwards (existing behaviour).
    let proposedAccountId: string | undefined;
    if (body.confirmHypothesis) {
      if (!c.proposedAccount) {
        throw badRequest(
          "This question does not have an AI hypothesis to confirm. " +
            "Answer it in your own words instead.",
        );
      }
      proposedAccountId = c.proposedAccount.id;
    }
    if (body.optionAccountId) {
      if (!publicChoices(c.options).some((o) => o.accountId === body.optionAccountId)) {
        throw badRequest("That option is not offered for this question.");
      }
      proposedAccountId = body.optionAccountId;
    }

    const updated = await answerClarification({
      firmId: ctx.firmId,
      clarificationId: c.id,
      answeredBy: "client:portal",
      answer: body.answer,
      // When set, answerClarification applies this account to the
      // underlying transaction as a MANUAL classification (confidence 1),
      // creates a reusable ClassificationRule, AND calls
      // propagateToPayeeSiblings to settle every other unresolved payment
      // to the same beneficiaryKey in this case — see
      // classification/learning.ts. That's the one-click group-assignment
      // the spec asked for.
      proposedAccountId,
    });

    res.json({
      ok: true,
      clarification: updated,
      // Tell the portal whether the group was actually settled (vs just
      // recorded as text) so it can show the right confirmation UI.
      groupSettled: !!proposedAccountId,
    });
  },
);
